-- PPG and PPS (176) on the college leaders view: columns appended, so CREATE OR REPLACE keeps the grants.
CREATE OR REPLACE VIEW public.college_v_player_leaders AS
 SELECT ps.player_id,
    p.display_name,
    p.suppress,
    ps.program_id,
    pr.name AS program_name,
    pr.gender,
    s.seo AS school_seo,
    s.logo_svg_url,
    ps.season,
    pse.division,
    pse.conference_id,
    c.name AS conference_name,
    pse.ncaa_member,
    ps.jersey,
    ps."position",
    ps.class_year,
    ps.class_raw,
    ps.height_cm,
    ps.headshot_url,
    st.player_season_id,
    st.gp,
    st.gs,
    st.minutes,
    st.goals,
    st.assists,
    st.points,
    st.shots,
    st.sog,
    st.pk_goals,
    st.pk_att,
    st.fouls,
    st.yc,
    st.rc,
    st.corners,
    st.offsides,
    st.gwg,
    st.hat_tricks,
    st.ga,
    st.saves,
    st.shutouts,
    st.gk_minutes,
    st.gk_wins,
    st.gk_losses,
    st.gk_ties,
    st.goals_p90,
    st.assists_p90,
    st.shots_p90,
    st.sog_p90,
    st.points_p90,
    st.shot_accuracy,
    st.conversion_pct,
    st.gaa,
    st.save_pct,
    st.minutes_share,
    st.computed_at,
    st.goals_1h,
    st.goals_2h,
    st.goals_ot,
    st.minutes_per_goal,
    st.shots_per_goal,
    st.pk_pct,
    st.clean_sheets,
    st.saves_p90,
    st.div_rank_points,
    st.div_rank_goals,
    st.div_rank_assists,
    st.conf_rank_points,
    st.conf_rank_goals,
    st.pct_points_p90,
    st.pct_goals_p90,
    st.pct_assists_p90,
    st.pct_shots_p90,
    st.pct_save_pct,
    st.pct_gaa,
    st.res_apps,
    st.res_pts,
    st.ppg,
    st.pps_starts,
    st.pps_pts,
    st.pps
   FROM college_player_season_stats st
     JOIN college_player_seasons ps ON ps.id = st.player_season_id
     JOIN college_players p ON p.id = ps.player_id
     JOIN college_programs pr ON pr.id = ps.program_id
     JOIN college_schools s ON s.seo = pr.school_seo
     LEFT JOIN college_program_seasons pse ON pse.program_id = ps.program_id AND pse.season = ps.season
     LEFT JOIN college_conferences c ON c.id = pse.conference_id;
